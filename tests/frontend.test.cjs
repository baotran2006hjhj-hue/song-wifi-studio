const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('web/app.js','utf8').split('// Event handlers use delegated listeners')[0];
const context=vm.createContext({document:{querySelector:()=>null},structuredClone,console});
vm.runInContext(source,context);
const run=code=>vm.runInContext(code,context);
run(`project=emptyProject(); project.plan.meters=30;`);
assert.ok(run(`predictedRssi({x:0,y:0,power:20,band:'5'},.1,0)>predictedRssi({x:0,y:0,power:20,band:'5'},.9,0)`),'Signal must decrease with distance');
const before=run(`predictedRssi({x:0,y:.5,power:20,band:'5'},1,.5)`);
run(`project.plan.walls=[{a:{x:.5,y:0},b:{x:.5,y:1},loss:8}]`);
assert.equal(run(`predictedRssi({x:0,y:.5,power:20,band:'5'},1,.5)`),before-8,'Crossed wall must subtract its loss');
assert.equal(run(`idw([{x:0,y:0,rssi:-50},{x:1,y:0,rssi:-70}],.5,0).value`),-60,'Interpolation between equal-distance points');
assert.equal(run(`idw([{x:.2,y:.4,rssi:-67}],.2,.4).value`),-67,'Measured points retain their exact RSSI');
assert.ok(run(`csvCell('=HYPERLINK("bad")')`).startsWith('"\''),'CSV must neutralize spreadsheet formulas');
assert.equal(run(`csvCell(-55)`),'"-55"','Numeric RSSI remains numeric');
assert.equal(run(`validateProject(emptyProject()).version`),1);
assert.throws(()=>run(`validateProject({...emptyProject(),plan:{...emptyProject().plan,meters:0}})`));
assert.throws(()=>run(`validateProject({...emptyProject(),survey:{image:'https://example.com/a.png',points:[],bssid:''}})`));
assert.throws(()=>run(`validateProject({...emptyProject(),plan:{...emptyProject().plan,aps:[{id:'bad',x:Infinity,y:0,power:20,band:'5'}]}})`));
const exported=JSON.parse(fs.readFileSync('tests/browser-project.json','utf8'));
context.exported=exported;
assert.equal(run(`validateProject(exported).plan.aps.length`),1,'Browser-exported project must round-trip');
assert.equal(run(`validateProject(exported).plan.walls.length`),1);
console.log('12 frontend checks passed: propagation, walls, interpolation, CSV safety, import validation and browser-export round-trip.');
